-- เสน่ห์ POS: ตารางทั้งหมดอยู่ใน schema "dbo" (ไม่เปิดผ่าน REST API ของ Supabase — เข้าได้ทางฟังก์ชัน pos เท่านั้น)
-- ชื่อคอลัมน์ตรงกับระบบเดิม (Google Sheet / SQL Server) ทุกตัว แต่เก็บเป็นตัวพิมพ์เล็กตามแบบ Postgres
-- BIT เดิม = smallint (0/1)
create schema if not exists dbo;
revoke all on schema dbo from public, anon, authenticated;

create table dbo.orders (
  rowid integer generated by default as identity primary key,
  "timestamp" varchar(40), ordernumber varchar(60), customername varchar(200), address varchar(300),
  itemdetail varchar(1000), diningoption varchar(100), price numeric(18,2), totalamount numeric(18,2),
  status varchar(30), orderstarttime varchar(40), completiontime varchar(40), recordedby varchar(120),
  quantity numeric(18,3), tslocal timestamp(3), branchid varchar(60)
);
create index ix_orders_ordernumber on dbo.orders (ordernumber);
create index ix_orders_tslocal on dbo.orders (tslocal);
create index ix_orders_status on dbo.orders (status);
create index ix_orders_branch on dbo.orders (branchid, rowid);

create table dbo.tableorders (
  rowid integer generated by default as identity primary key,
  tablenumber varchar(50), sessionid varchar(80), itemname varchar(300), itemnameen varchar(300),
  itemprice numeric(18,2), quantity numeric(18,3), options text, "timestamp" varchar(40),
  status varchar(30), recordedby varchar(120), branchid varchar(60),
  kitchenprinted smallint  -- 0 = ลูกค้าสั่งผ่าน QR ยังไม่ได้พิมพ์ใบครัว · 1 = พิมพ์แล้ว · null = พนักงานสั่ง (พิมพ์ที่เครื่องตัวเอง)
);
create index ix_tableorders_table on dbo.tableorders (tablenumber);
create index ix_tableorders_session on dbo.tableorders (sessionid);
create index ix_tableorders_branch on dbo.tableorders (branchid, tablenumber);
create index ix_tableorders_kitchen on dbo.tableorders (branchid, kitchenprinted) where kitchenprinted = 0;

create table dbo.menu (
  seq integer generated by default as identity, id varchar(60) primary key,
  category varchar(100), name varchar(300), nameen varchar(300), description text, descriptionen text,
  price numeric(18,2), image text, isactive smallint, bundleditems text, popupconfig text, prices text,
  categories text, printerid varchar(60), sortorder integer, branches text, memberonly smallint
);

create table dbo.categories (
  seq integer generated by default as identity, slug varchar(100) primary key,
  name varchar(200), nameen varchar(200), icon varchar(20), isactive smallint,
  haspopup1 smallint, popup1category varchar(100), popup1items text, popup1min integer, popup1max integer, popup1itemsmax text, popup1free smallint,
  haspopup2 smallint, popup2category varchar(100), popup2items text, popup2min integer, popup2max integer, popup2itemsmax text, popup2free smallint,
  haspopup3 smallint, popup3category varchar(100), popup3items text, popup3min integer, popup3max integer, popup3itemsmax text, popup3free smallint,
  haspopup4 smallint, popup4category varchar(100), popup4items text, popup4min integer, popup4max integer, popup4itemsmax text, popup4free smallint,
  haspopup5 smallint, popup5category varchar(100), popup5items text, popup5min integer, popup5max integer, popup5itemsmax text, popup5free smallint,
  haspopup6 smallint, popup6category varchar(100), popup6items text, popup6min integer, popup6max integer, popup6itemsmax text, popup6free smallint,
  hasdining smallint, visibility varchar(20)
);

create table dbo.promotions (
  seq integer generated by default as identity, id varchar(60) primary key,
  name varchar(300), nameen varchar(300), price numeric(18,2), origprice varchar(50)
);

create table dbo.users (
  seq integer generated by default as identity, id varchar(60) primary key,
  username varchar(120), pin varchar(20), cancheckout smallint, isadmin smallint, iscashier smallint, branch varchar(120)
);

create table dbo.discounts (
  seq integer generated by default as identity, id varchar(60) primary key,
  name varchar(200), type varchar(40), value numeric(18,2), categories text
);

create table dbo.settings ("key" varchar(100) primary key, "value" text);

create table dbo.printers (
  seq integer generated by default as identity, id varchar(60) primary key,
  name varchar(200), ip varchar(60), type varchar(40), printmode varchar(40), branchid varchar(60), categories text
);

create table dbo.liquorstorage (
  rowid integer generated by default as identity primary key,
  "timestamp" varchar(40), type varchar(40), customername varchar(200), phone varchar(40), productname varchar(300),
  qty numeric(18,3), note text, staff varchar(120), category varchar(100), unit varchar(40)
);

create table dbo.waste (
  rowid integer generated by default as identity primary key,
  "timestamp" varchar(40), branch varchar(120), itemname varchar(300), category varchar(100), qty numeric(18,3),
  unit varchar(40), note text, staff varchar(120), tslocal timestamp(3), kind varchar(20), itemtype varchar(20)
);
create index ix_waste_tslocal on dbo.waste (tslocal);

create table dbo.paymentapprovals (
  rowid integer generated by default as identity primary key,
  id varchar(80), "timestamp" varchar(40), tableno varchar(50), ordernumber varchar(60), amount numeric(18,2),
  requestedby varchar(120), status varchar(30), approver varchar(120), respondedat varchar(40)
);
create index ix_paymentapprovals_id on dbo.paymentapprovals (id);

create table dbo.outstandingbills (
  rowid integer generated by default as identity primary key,
  id varchar(120), shiftid varchar(60), tableno varchar(50), customername varchar(200), phone varchar(40),
  total numeric(18,2), items text, createdat varchar(40), status varchar(30)
);

create table dbo.shifts (
  seq integer generated by default as identity, id varchar(60) primary key,
  opentime varchar(40), closetime varchar(40), openstaff varchar(120), closestaff varchar(120),
  opencash numeric(18,2), closecash numeric(18,2), totalsales numeric(18,2), totalcash numeric(18,2),
  totalcard numeric(18,2), totaltransfer numeric(18,2), totalorders numeric(18,2), status varchar(20), note text
);

create table dbo.paymentsummary (
  rowid integer generated by default as identity primary key,
  "timestamp" varchar(40), ordernumber varchar(60), tableno varchar(50), paymentmethod varchar(100),
  grandtotal numeric(18,2), staff varchar(120), shiftid varchar(60), splitdetail text,
  clientref varchar(60), branchid varchar(60), discountname varchar(200), discountamount numeric(12,2), discountkind varchar(10)
);
create index ix_paymentsummary_ordernumber on dbo.paymentsummary (ordernumber);
create index ix_paymentsummary_clientref on dbo.paymentsummary (clientref);

create table dbo.ingredients (
  seq integer generated by default as identity, id varchar(60) primary key,
  name varchar(300), nameen varchar(300), unit varchar(40), minstock numeric(18,3), costperunit numeric(18,4),
  category varchar(100), note text, purchaseunit varchar(40), unitsperpurchase numeric(18,4)
);

create table dbo.bom (
  rowid integer generated by default as identity primary key,
  menuid varchar(60), menuname varchar(300), menunameen varchar(300), ingid varchar(60), ingname varchar(300),
  qty numeric(18,4), unit varchar(40), costperunit numeric(18,4), note text
);
create index ix_bom_menuid on dbo.bom (menuid);

create table dbo.stockin (
  rowid integer generated by default as identity primary key,
  ts timestamp(3), ingid varchar(60), ingname varchar(300), usageqty numeric(18,4), usageunit varchar(40),
  costperusageunit numeric(18,4), total numeric(18,2), staff varchar(120), note text,
  purchaseqty numeric(18,4), purchaseunit varchar(40), priceperpurchase numeric(18,4), branchid varchar(60)
);
create index ix_stockin_branch on dbo.stockin (branchid, ingid);

create table dbo.stockout (
  rowid integer generated by default as identity primary key,
  ts timestamp(3), ordernumber varchar(60), tableno varchar(50), menuid varchar(60), menuname varchar(300),
  menuqty numeric(18,3), ingid varchar(60), ingname varchar(300), deductqty numeric(18,4), unit varchar(40),
  cost numeric(18,4), branchid varchar(60)
);
create index ix_stockout_branch on dbo.stockout (branchid, ingid);

create table dbo.branches (
  seq integer generated by default as identity, id varchar(60) primary key,
  name varchar(200), billprefix varchar(20), phone varchar(60), address varchar(500), taxid varchar(40),
  receiptfooter varchar(500), isactive smallint, posid varchar(40)
);

create table dbo.menubranch (
  menuid varchar(60) not null, branchid varchar(60) not null, isavailable smallint, pricemap text, printerid varchar(60),
  primary key (menuid, branchid)
);

create table dbo.taxinvoices (
  rowid integer generated by default as identity primary key,
  invoiceno varchar(60) not null unique, ordernumber varchar(60) not null, branchid varchar(60), issuedat varchar(40),
  buyername varchar(300), buyertaxid varchar(40), buyeraddress varchar(1000), buyerbranch varchar(100),
  itemsjson text, subtotal numeric(18,2), vatrate numeric(9,2), vatamount numeric(18,2), total numeric(18,2),
  sellerjson text, issuedby varchar(120), cancelled smallint, cancelledat varchar(40), cancelreason varchar(500)
);
create index ix_taxinvoices_order on dbo.taxinvoices (ordernumber);

create table dbo.taxcustomers (
  taxid varchar(20) not null, buyerbranch varchar(100) not null, name varchar(300), address varchar(1000),
  phone varchar(60), usecount integer, lastusedat varchar(40), primary key (taxid, buyerbranch)
);

create table dbo.kioskpayments (
  rowid integer generated by default as identity, id varchar(60) primary key,
  branchid varchar(60), tableno varchar(50), dining varchar(50), payloadjson text, total numeric(18,2),
  status varchar(20), requestedat varchar(40), respondedat varchar(40), respondedby varchar(120), ordernumber varchar(60)
);
create index ix_kioskpayments_status on dbo.kioskpayments (status, branchid, requestedat);

create table dbo.crmbills (
  rowid integer generated by default as identity primary key,
  branchid varchar(60) not null, ordernumber varchar(60) not null, memberid varchar(20), payloadjson text not null,
  status varchar(20) not null default 'pending', attempts integer not null default 0,
  nextattempt timestamp(0) not null default (now() at time zone 'utc'), lasterror varchar(500),
  points integer, balance integer, createdat timestamp(0) not null default (now() at time zone 'utc'), sentat timestamp(0),
  unique (branchid, ordernumber)
);
create index ix_crmbills_pending on dbo.crmbills (status, nextattempt);

create table dbo.printjobs (
  rowid integer generated by default as identity primary key,
  jobid varchar(40) not null unique, branchid varchar(60) not null, printerip varchar(100) not null,
  printername varchar(120), printertype varchar(20) not null, payloadjson text not null, label varchar(120),
  status varchar(20) not null default 'pending', stage varchar(20), error varchar(500), warning varchar(500),
  confirmed smallint, stepsjson text, createdat timestamp(0) not null default (now() at time zone 'utc'),
  claimedat timestamp(0), claimedby varchar(120), finishedat timestamp(0)
);
create index ix_printjobs_queue on dbo.printjobs (branchid, status, rowid);

create table dbo.printagents (
  branchid varchar(60) primary key, agent varchar(120), version varchar(20), lastseen timestamp(0) not null
);

create table dbo.membermenuusage (
  rowid integer generated by default as identity primary key,
  memberid varchar(20) not null, menuid varchar(60) not null, menuname varchar(300), qty integer not null,
  channel varchar(10) not null, branchid varchar(60), orderref varchar(80) not null, ordernumber varchar(60),
  status varchar(10) not null, usageday varchar(10) not null, createdat timestamp(0) not null default (now() at time zone 'utc')
);
create index ix_membermenuusage_member on dbo.membermenuusage (memberid, usageday);
create index ix_membermenuusage_ref on dbo.membermenuusage (orderref);
create index ix_membermenuusage_day on dbo.membermenuusage (usageday);

create table dbo.billcounters (
  prefix varchar(60) primary key, lastno integer not null, updatedat timestamp(0) not null default (now() at time zone 'utc')
);
;

